<?php

declare(strict_types=1);

/*
 * Runs a PHP language server over this lane's hover, document_symbol, call_hierarchy and
 * implementation keys and writes what it answered next to what the key says (checklist E.5).
 * The key is never changed from here: where the server and a key disagree, the tree decides.
 *
 *   php bench/lsp_check.php --plan
 *       No server. Prints the request each task makes (method, file, line, column) and exits 0
 *       when every task resolves to one position; tests/Feature/LspCheckPlanTest.php runs this.
 *   php bench/lsp_check.php --server "php phpactor.phar language-server" \
 *       --name phpactor --server-version 2026.11.22.0 [--wait 40] [--out bench/lsp-check.md] [--append]
 *       Without --append the report file is rewritten with a title and this server's section;
 *       with it, this server's section is added below what the file already holds.
 *       Starts the server over stdio with this lane directory as the workspace root, waits for
 *       it to index, asks every task, and writes the report (lane-relative paths only).
 *
 * Plain PHP and JSON-RPC over pipes: no composer dependency.
 */

const SURFACES = ['hover', 'document_symbol', 'call_hierarchy', 'implementation'];

$lane = dirname(__DIR__);
$opts = parse_options($argv);
$tasks = plan_tasks($lane);

if (isset($opts['plan'])) {
    foreach ($tasks as $t) {
        printf("%s %s %s %s:%d:%d\n", $t['id'], $t['surface'], implode('+', $t['methods']), $t['file'], $t['line'], $t['column']);
    }
    printf("plan: %d tasks over %s\n", count($tasks), implode(', ', SURFACES));
    exit(0);
}

if (! isset($opts['server'])) {
    fwrite(STDERR, "usage: php bench/lsp_check.php --plan | --server <command> --name <n> --server-version <v> [--wait <s>] [--out <file>] [--append]\n");
    exit(2);
}

$client = new LspClient($opts['server'], $lane);
$init = $client->request('initialize', [
    'processId' => getmypid(),
    'rootUri' => file_uri($lane),
    'rootPath' => $lane,
    'workspaceFolders' => [['uri' => file_uri($lane), 'name' => 'php']],
    'capabilities' => [
        'textDocument' => [
            'hover' => ['contentFormat' => ['markdown', 'plaintext']],
            'documentSymbol' => ['hierarchicalDocumentSymbolSupport' => true],
            'callHierarchy' => ['dynamicRegistration' => false],
            'implementation' => ['linkSupport' => false],
        ],
        'workspace' => ['workspaceFolders' => true, 'configuration' => true],
    ],
]);
$caps = $init['result']['capabilities'] ?? [];
$client->notify('initialized', new stdClass());
$client->drain((int) ($opts['wait'] ?? 40));

$rows = [];
foreach ($tasks as $t) {
    $client->open($t['file']);
    $rows[] = [$t['id'], $t['surface'], ...ask($client, $t, $lane)];
}
$client->shutdown();

$capLine = [];
foreach (['hoverProvider' => 'hover', 'documentSymbolProvider' => 'document_symbol', 'callHierarchyProvider' => 'call_hierarchy', 'implementationProvider' => 'implementation'] as $cap => $surface) {
    $capLine[] = $surface . ': ' . (empty($caps[$cap]) ? 'not advertised' : 'advertised');
}
$counts = array_count_values(array_column($rows, 2));
ksort($counts);
$out = isset($opts['append']) ? "\n" : "# Language-server check (php lane, checklist E.5)\n\nWritten by `php bench/lsp_check.php` (see php/README.md, section E.5). The answer keys are the tree's; a disagreement is read against the tree and written down, never fixed by changing a key to the server's reply.\n\n";
$out .= sprintf("## %s %s\n\n", $opts['name'] ?? '?', $opts['server-version'] ?? '?');
$out .= sprintf("Command: `%s`, workspace root: this lane directory (`php/`), after `composer install`.\n", sanitize_command($opts['server']));
$out .= sprintf("Generated by `php bench/lsp_check.php` on %s (UTC) after a %d s index wait.\n\n", gmdate('Y-m-d'), (int) ($opts['wait'] ?? 40));
$out .= 'Advertised in `initialize`: ' . implode('; ', $capLine) . ".\n\n";
$out .= 'Verdicts: ' . implode(', ', array_map(fn ($k, $v) => "$k $v", array_keys($counts), $counts)) . ".\n\n";
$out .= "| Task | Surface | Verdict | What the server returned |\n| --- | --- | --- | --- |\n";
foreach ($rows as [$id, $surface, $verdict, $detail]) {
    $out .= sprintf("| `%s` | %s | %s | %s |\n", $id, $surface, $verdict, str_replace(['|', "\n"], ['\\|', ' '], $detail));
}
$target = $opts['out'] ?? ($lane . '/bench/lsp-check.md');
isset($opts['append']) ? file_put_contents($target, $out, FILE_APPEND) : file_put_contents($target, $out);
printf("wrote %s (%d tasks: %s)\n", $target, count($rows), json_encode($counts));

// ---------------------------------------------------------------------------------------------

function parse_options(array $argv): array
{
    $opts = [];
    for ($i = 1; $i < count($argv); $i++) {
        if (! str_starts_with($argv[$i], '--')) {
            continue;
        }
        $key = substr($argv[$i], 2);
        if ($key === 'plan' || $key === 'append') {
            $opts[$key] = true;
        } else {
            $opts[$key] = $argv[++$i] ?? '';
        }
    }

    return $opts;
}

/** Every task on the four surfaces, with the 1-based line and 0-based column it is asked at. */
function plan_tasks(string $lane): array
{
    $data = json_decode((string) file_get_contents($lane . '/bench/tasks.json'), true, 512, JSON_THROW_ON_ERROR);
    $out = [];
    foreach ($data['tasks'] as $task) {
        if (! in_array($task['surface'], SURFACES, true)) {
            continue;
        }
        $from = $task['from'];
        $line = needle_line($lane, $from['file'], $from['needle']);
        $text = file($lane . '/' . $from['file'], FILE_IGNORE_NEW_LINES)[$line - 1];
        $column = 0;
        if ($task['surface'] !== 'document_symbol') {
            $columns = symbol_columns($text, $from['symbol']);
            $at = $columns[($from['occurrence'] ?? 1) - 1] ?? null;
            if ($at === null) {
                throw new RuntimeException("{$task['id']}: symbol {$from['symbol']} not on its from line");
            }
            // Inside the identifier, not on its first byte: a `$` or a boundary can miss.
            $column = $at + intdiv(strlen($from['symbol']), 2);
        }
        $methods = match ($task['surface']) {
            'hover' => ['textDocument/hover'],
            'document_symbol' => ['textDocument/documentSymbol'],
            'implementation' => ['textDocument/implementation'],
            'call_hierarchy' => ['textDocument/prepareCallHierarchy', isset($task['expect']['incoming_includes']) ? 'callHierarchy/incomingCalls' : 'callHierarchy/outgoingCalls'],
        };
        $out[] = ['id' => $task['id'], 'surface' => $task['surface'], 'file' => $from['file'], 'line' => $line, 'column' => $column, 'methods' => $methods, 'expect' => $task['expect']];
    }

    return $out;
}

/** The 1-based line a needle names; it must name exactly one line, as the verifier demands. */
function needle_line(string $lane, string $file, string $needle): int
{
    $hits = [];
    foreach (file($lane . '/' . $file, FILE_IGNORE_NEW_LINES) as $i => $text) {
        if (str_contains($text, $needle)) {
            $hits[] = $i + 1;
        }
    }
    if (count($hits) !== 1) {
        throw new RuntimeException("$file: needle matches " . count($hits) . ' lines: ' . $needle);
    }

    return $hits[0];
}

/** Same rule as bench/score/lib/symbol.mjs: whole-identifier occurrences only. */
function symbol_columns(string $line, string $symbol): array
{
    $word = fn (string $c): bool => $c !== '' && preg_match('/[A-Za-z0-9_]/', $c) === 1;
    $left = $word($symbol[0]);
    $right = $word($symbol[strlen($symbol) - 1]);
    $out = [];
    for ($at = strpos($line, $symbol); $at !== false; $at = strpos($line, $symbol, $at + 1)) {
        $before = $at === 0 ? '' : $line[$at - 1];
        $after = $line[$at + strlen($symbol)] ?? '';
        if (($left && $word($before)) || ($right && $word($after))) {
            continue;
        }
        $out[] = $at;
    }

    return $out;
}

/** @return array{string, string} verdict and a short account of the reply */
function ask(LspClient $client, array $t, string $lane): array
{
    $doc = ['uri' => file_uri($lane . '/' . $t['file'])];
    $pos = ['line' => $t['line'] - 1, 'character' => $t['column']];
    $e = $t['expect'];

    if ($t['surface'] === 'hover') {
        $r = $client->request('textDocument/hover', ['textDocument' => $doc, 'position' => $pos]);
        if (isset($r['error']) || empty($r['result'])) {
            return ['server has no answer', describe_error($r)];
        }
        $text = hover_text($r['result']['contents'] ?? '');
        $ok = str_contains($text, $e['contains']);

        return [$ok ? 'agrees' : 'disagrees', sprintf('%s "%s"; hover: %s', $ok ? 'contains' : 'lacks', $e['contains'], short($text))];
    }

    if ($t['surface'] === 'document_symbol') {
        $r = $client->request('textDocument/documentSymbol', ['textDocument' => $doc]);
        if (isset($r['error']) || ! is_array($r['result'] ?? null)) {
            return ['server has no answer', describe_error($r)];
        }
        $names = symbol_names($r['result']);
        $missing = array_values(array_diff($e['must_include'], $names));
        $ok = count($names) >= $e['min_symbols'] && $missing === [];

        return [$ok ? 'agrees' : 'disagrees', sprintf('%d symbols (key: min_symbols %d, N = %d): %s%s', count($names), $e['min_symbols'], count($e['symbols']), implode(', ', $names), $missing ? '; missing ' . implode(', ', $missing) : '')];
    }

    if ($t['surface'] === 'implementation') {
        $r = $client->request('textDocument/implementation', ['textDocument' => $doc, 'position' => $pos]);
        if (isset($r['error']) || $r['result'] === null) {
            return ['server has no answer', describe_error($r)];
        }
        $got = array_unique(array_map(fn ($l) => location_key($l, $lane), is_array($r['result']) && array_is_list($r['result']) ? $r['result'] : [$r['result']]));
        $want = array_map(fn ($s) => $s['file'] . ':' . needle_line($lane, $s['file'], $s['needle']), $e['implementations'] ?? [['file' => $e['file'], 'needle' => $e['needle']]]);
        $optional = array_map(fn ($s) => $s['file'] . ':' . needle_line($lane, $s['file'], $s['needle']), $e['optional_sites'] ?? []);
        $missing = array_values(array_diff($want, $got));
        $extra = array_values(array_diff($got, $want, $optional));
        $ok = $missing === [] && $extra === [];

        return [$ok ? 'agrees' : 'disagrees', sprintf('%d locations (key: %d%s)%s%s', count($got), count($want), $optional ? ', ' . count($optional) . ' optional' : '', $missing ? '; key lines not returned: ' . implode(', ', $missing) : '', $extra ? '; returned beyond the key: ' . implode(', ', array_slice($extra, 0, 8)) . (count($extra) > 8 ? ', ...' : '') : '')];
    }

    // call_hierarchy
    $r = $client->request('textDocument/prepareCallHierarchy', ['textDocument' => $doc, 'position' => $pos]);
    if (isset($r['error']) || empty($r['result'])) {
        return ['server has no answer', 'prepareCallHierarchy: ' . describe_error($r)];
    }
    $item = $r['result'][0];
    $incoming = isset($e['incoming_includes']);
    $r2 = $client->request($incoming ? 'callHierarchy/incomingCalls' : 'callHierarchy/outgoingCalls', ['item' => $item]);
    if (isset($r2['error']) || ! is_array($r2['result'] ?? null)) {
        return ['server has no answer', describe_error($r2)];
    }
    $found = [];
    $notFound = [];
    foreach ($incoming ? $e['incoming_includes'] : $e['outgoing_includes'] as $site) {
        $line = needle_line($lane, $site['file'], $site['needle']) - 1;
        $hit = false;
        foreach ($r2['result'] as $call) {
            $peer = $incoming ? $call['from'] : $call['to'];
            if (location_file($peer['uri'], $lane) !== $site['file']) {
                continue;
            }
            $ranges = $incoming ? ($call['fromRanges'] ?? []) : [$peer['selectionRange']];
            $ranges[] = $peer['range'];
            foreach ($ranges as $range) {
                if ($range['start']['line'] <= $line && $line <= $range['end']['line']) {
                    $hit = true;
                }
            }
        }
        $hit ? $found[] = $site['file'] . ':' . ($line + 1) : $notFound[] = $site['file'] . ':' . ($line + 1);
    }
    $ok = $notFound === [] && (! $incoming || count($r2['result']) >= $e['min_incoming']);

    return [$ok ? 'agrees' : 'disagrees', sprintf('%d %s calls%s%s', count($r2['result']), $incoming ? 'incoming' : 'outgoing', $found ? '; listed sites found: ' . implode(', ', $found) : '', $notFound ? '; listed sites NOT found: ' . implode(', ', $notFound) : '')];
}

function hover_text(mixed $contents): string
{
    if (is_string($contents)) {
        return $contents;
    }
    if (isset($contents['value'])) {
        return (string) $contents['value'];
    }
    if (is_array($contents)) {
        return implode("\n", array_map('hover_text', $contents));
    }

    return '';
}

function symbol_names(array $symbols): array
{
    $names = [];
    foreach ($symbols as $s) {
        $names[] = ltrim((string) $s['name'], '$');
        if (! empty($s['children'])) {
            array_push($names, ...symbol_names($s['children']));
        }
    }

    return $names;
}

function location_key(array $loc, string $lane): string
{
    $uri = $loc['uri'] ?? $loc['targetUri'];
    $range = $loc['range'] ?? $loc['targetSelectionRange'];

    return location_file($uri, $lane) . ':' . ($range['start']['line'] + 1);
}

function location_file(string $uri, string $lane): string
{
    $path = rawurldecode(preg_replace('#^file://#', '', $uri));
    $prefix = rtrim($lane, '/') . '/';

    return str_starts_with($path, $prefix) ? substr($path, strlen($prefix)) : '<outside the lane>/' . basename($path);
}

function describe_error(array $r): string
{
    if (isset($r['error'])) {
        return sprintf('error %s %s', $r['error']['code'] ?? '?', short((string) ($r['error']['message'] ?? '')));
    }

    return 'null result';
}

function short(string $text): string
{
    $text = trim(preg_replace('/\s+/', ' ', $text));

    return strlen($text) > 160 ? substr($text, 0, 157) . '...' : $text;
}

function file_uri(string $path): string
{
    return 'file://' . str_replace('%2F', '/', rawurlencode($path));
}

/** The report is public: keep only basenames of the paths in the server command. */
function sanitize_command(string $command): string
{
    return implode(' ', array_map(fn ($w) => str_contains($w, '/') ? basename($w) : $w, explode(' ', $command)));
}

final class LspClient
{
    private $proc;

    private array $pipes = [];

    private int $id = 0;

    private string $buffer = '';

    public function __construct(string $command, private string $lane)
    {
        $this->proc = proc_open($command, [0 => ['pipe', 'r'], 1 => ['pipe', 'w'], 2 => ['file', '/dev/null', 'a']], $this->pipes, $lane);
        if (! is_resource($this->proc)) {
            throw new RuntimeException("cannot start: $command");
        }
        stream_set_blocking($this->pipes[1], false);
    }

    public function request(string $method, array|object $params, int $timeout = 60): array
    {
        $id = ++$this->id;
        $this->send(['jsonrpc' => '2.0', 'id' => $id, 'method' => $method, 'params' => $params]);
        $deadline = microtime(true) + $timeout;
        while (microtime(true) < $deadline) {
            $msg = $this->read(1.0);
            if ($msg === null) {
                continue;
            }
            if (($msg['id'] ?? null) === $id && ! isset($msg['method'])) {
                return $msg;
            }
            $this->answerServer($msg);
        }

        return ['error' => ['code' => 'timeout', 'message' => "no reply to $method in {$timeout}s"]];
    }

    public function notify(string $method, array|object $params): void
    {
        $this->send(['jsonrpc' => '2.0', 'method' => $method, 'params' => $params]);
    }

    public function open(string $file): void
    {
        static $opened = [];
        if (isset($opened[$file])) {
            return;
        }
        $opened[$file] = true;
        $this->notify('textDocument/didOpen', ['textDocument' => [
            'uri' => file_uri($this->lane . '/' . $file), 'languageId' => 'php', 'version' => 1,
            'text' => (string) file_get_contents($this->lane . '/' . $file),
        ]]);
    }

    /** Read and answer whatever the server sends for $seconds (its indexing time). */
    public function drain(int $seconds): void
    {
        $deadline = microtime(true) + $seconds;
        while (microtime(true) < $deadline) {
            $msg = $this->read(1.0);
            if ($msg !== null) {
                $this->answerServer($msg);
            }
        }
    }

    public function shutdown(): void
    {
        $this->request('shutdown', new stdClass(), 10);
        $this->notify('exit', new stdClass());
        foreach ($this->pipes as $pipe) {
            fclose($pipe);
        }
        proc_terminate($this->proc);
    }

    private function answerServer(array $msg): void
    {
        if (isset($msg['id'], $msg['method'])) {
            $result = $msg['method'] === 'workspace/configuration' ? array_fill(0, count($msg['params']['items'] ?? []), null) : null;
            $this->send(['jsonrpc' => '2.0', 'id' => $msg['id'], 'result' => $result]);
        }
    }

    private function send(array $msg): void
    {
        $body = json_encode($msg, JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR);
        fwrite($this->pipes[0], 'Content-Length: ' . strlen($body) . "\r\n\r\n" . $body);
        fflush($this->pipes[0]);
    }

    private function read(float $timeout): ?array
    {
        $deadline = microtime(true) + $timeout;
        while (true) {
            if (preg_match('/Content-Length: (\d+)\r\n/i', $this->buffer, $m) && ($head = strpos($this->buffer, "\r\n\r\n")) !== false) {
                $length = (int) $m[1];
                if (strlen($this->buffer) >= $head + 4 + $length) {
                    $body = substr($this->buffer, $head + 4, $length);
                    $this->buffer = substr($this->buffer, $head + 4 + $length);

                    return json_decode($body, true) ?? [];
                }
            }
            $left = $deadline - microtime(true);
            if ($left <= 0) {
                return null;
            }
            $read = [$this->pipes[1]];
            $write = $except = null;
            if (@stream_select($read, $write, $except, 0, (int) ($left * 1e6)) > 0) {
                $chunk = fread($this->pipes[1], 65536);
                if ($chunk === '' || $chunk === false) {
                    if (feof($this->pipes[1])) {
                        return null;
                    }
                } else {
                    $this->buffer .= $chunk;
                }
            }
        }
    }
}
